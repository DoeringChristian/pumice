// Builds runtime/main.ts into one script, kept as a string in src/runtime.generated.ts.
// Usage: node plugins/core-export/scripts/build-runtime.mjs [--check]
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../src/runtime.generated.ts');

export async function runtimeSource() {
  const result = await build({
    entryPoints: [join(here, '../runtime/main.ts')],
    bundle: true,
    format: 'iife',
    minify: true,
    target: 'es2020',
    write: false,
    legalComments: 'none',
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text.trim();
  return `// Generated by scripts/build-runtime.mjs from runtime/main.ts. Do not edit.\n/* eslint-disable */\n// prettier-ignore\nexport const RUNTIME_JS: string = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await runtimeSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== next) {
      console.error(
        'runtime.generated.ts is out of date: run node plugins/core-export/scripts/build-runtime.mjs',
      );
      process.exit(1);
    }
  } else {
    writeFileSync(out, next);
    console.log(`wrote ${out} (${next.length} bytes)`);
  }
}
