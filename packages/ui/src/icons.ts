export function registerIcon(name: string, node: IconNode): void {
  registry.set(name, node);
}

/** Creates an icon element. Unknown names render as text (so emoji work as icons). */
export function createIcon(name: string, size = 16): Element {
  const node = registry.get(name);
  if (!node) {
    const span = document.createElement('span');
    span.textContent = name;
    span.style.fontSize = `${size - 2}px`;
    span.style.lineHeight = '1';
    return span;
  }
  const svg = createElement(node);
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('stroke-width', '1.75');
  svg.setAttribute('aria-hidden', 'true');
  return svg;
}
